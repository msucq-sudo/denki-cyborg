import type { EnemyKind } from './balance';

/** 敵の表示名・説明（HUD・敵図鑑が参照）。数値は balance.ts の ENEMIES */
export interface EnemyInfo {
  name: string;
  /** 一言の役割 */
  role: string;
  /** 行動の説明（箇条書き） */
  behavior: string[];
  weakness: string;
  /** 初登場エリア */
  area: string;
  /** 見た目のメモ */
  look: string;
}

// 既存の図鑑番号（No.01〜08）は変えない。Phase 3 の新しい雑魚は No.09 から後ろに足す
